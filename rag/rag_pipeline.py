# ==== CẤU HÌNH ====
CLIP_MODEL_NAME = "openai/clip-vit-base-patch32"
# Cùng thư mục + cùng collection với rag_vqa_pipeline.py để tái sử dụng index
CHROMA_DIR = "/content/drive/MyDrive/VQA_project/chroma_charxiv"
COLLECTION_NAME = "charxiv_validation_images"
N_CHARTS = 500                # đồng bộ với baseline_qwen.py và rag_vqa_pipeline.py
TOP_K_LIST = [1, 3, 5, 10]
RETRIEVAL_EVAL_FILE = "/content/drive/MyDrive/VQA_project/retrieval_eval_results.csv"


def get_device():
    return "cuda" if torch.cuda.is_available() else "cpu"


def load_clip():
    device = get_device()
    print(f"Đang tải CLIP ({CLIP_MODEL_NAME}) lên {device}...")
    model = CLIPModel.from_pretrained(CLIP_MODEL_NAME).to(device).eval()
    processor = CLIPProcessor.from_pretrained(CLIP_MODEL_NAME)
    return model, processor, device


@torch.no_grad()
def embed_images(model, processor, device, images):
    """Gọi trực tiếp vision_model + visual_projection thay vì
    get_image_features() — một số bản transformers có lỗi ở hàm đó (trả về
    thẳng output thô, thiếu chiếu qua lớp projection)."""
    inputs = processor(images=images, return_tensors="pt").to(device)
    vision_outputs = model.vision_model(pixel_values=inputs["pixel_values"])
    pooled_output = vision_outputs.pooler_output
    feats = model.visual_projection(pooled_output)
    feats = feats / feats.norm(p=2, dim=-1, keepdim=True)
    return feats.cpu().numpy()


@torch.no_grad()
def embed_texts(model, processor, device, texts):
    """Tương tự embed_images — gọi trực tiếp text_model + text_projection."""
    inputs = processor(text=texts, return_tensors="pt", padding=True, truncation=True).to(device)
    text_outputs = model.text_model(
        input_ids=inputs["input_ids"],
        attention_mask=inputs.get("attention_mask"),
    )
    pooled_output = text_outputs.pooler_output
    feats = model.text_projection(pooled_output)
    feats = feats / feats.norm(p=2, dim=-1, keepdim=True)
    return feats.cpu().numpy()


def get_collection():
    client = chromadb.PersistentClient(path=CHROMA_DIR)
    return client.get_or_create_collection(
        name=COLLECTION_NAME,
        metadata={"hnsw:space": "cosine"},
    )


def build_index(val_ds, model, processor, device, n_charts, batch_size=16):
    """Chỉ mã hoá thêm ảnh còn thiếu — nếu đã build từ rag_vqa_pipeline.py
    rồi thì phần lớn (hoặc toàn bộ) sẽ được tái sử dụng, không làm lại."""
    collection = get_collection()

    existing_ids = set(collection.get()["ids"]) if collection.count() > 0 else set()
    todo = [i for i in range(n_charts) if str(i) not in existing_ids]

    if not todo:
        print(f"Index đã có đủ {n_charts} ảnh, bỏ qua bước build.")
        return collection

    print(f"Đang mã hoá {len(todo)} ảnh còn thiếu vào vector DB...")
    for start in tqdm(range(0, len(todo), batch_size)):
        batch_idx = todo[start:start + batch_size]
        images = [val_ds[i]["image"].convert("RGB") for i in batch_idx]
        embeddings = embed_images(model, processor, device, images)

        collection.add(
            ids=[str(i) for i in batch_idx],
            embeddings=embeddings.tolist(),
            metadatas=[{"chart_index": i} for i in batch_idx],
        )

    print(f"Hoàn tất: vector DB hiện có {collection.count()} ảnh.")
    return collection


def evaluate_retrieval(val_ds, model, processor, device, collection, n_charts):
    max_k = max(TOP_K_LIST)
    rows = []

    print(f"Đang đánh giá retrieval trên {n_charts} câu hỏi reasoning...")
    for chart_idx in tqdm(range(n_charts)):
        question = val_ds[chart_idx]["reasoning_q"]
        query_emb = embed_texts(model, processor, device, [question])[0]

        result = collection.query(
            query_embeddings=[query_emb.tolist()],
            n_results=max_k,
        )
        retrieved_ids = [int(x) for x in result["ids"][0]]

        row = {"chart_index": chart_idx, "question": question}
        for k in TOP_K_LIST:
            row[f"hit@{k}"] = chart_idx in retrieved_ids[:k]
        row["rank_of_correct"] = (
            retrieved_ids.index(chart_idx) + 1 if chart_idx in retrieved_ids else None
        )
        rows.append(row)

    df = pd.DataFrame(rows)
    df.to_csv(RETRIEVAL_EVAL_FILE, index=False, encoding="utf-8-sig")

    print(f"\n=== Kết quả Retrieval Hit@k trên {len(df)} câu hỏi ===")
    for k in TOP_K_LIST:
        print(f"Hit@{k}: {df[f'hit@{k}'].mean():.2%}")
    print(f"\nĐã lưu chi tiết vào '{RETRIEVAL_EVAL_FILE}'")
    return df


def retrieve_for_query(question: str, model, processor, device, collection, top_k=5):
    query_emb = embed_texts(model, processor, device, [question])[0]
    result = collection.query(query_embeddings=[query_emb.tolist()], n_results=top_k)
    return [int(x) for x in result["ids"][0]]



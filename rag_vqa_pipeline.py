N_CHARTS = 500                         # giữ giống 2 file kia để so sánh công bằng
MAX_IMAGE_SIDE = 1024
MAX_NEW_TOKENS = 64
UNANSWERABLE_LABEL = "Not Applicable"
LOAD_IN_4BIT = True                  # đặt False nếu có GPU >=24GB VRAM

# ==== CẤU HÌNH RETRIEVAL (CLIP + ChromaDB) — giữ giống rag_pipeline.py ====
CLIP_MODEL_NAME = "openai/clip-vit-base-patch32"
CHROMA_DIR = "/content/drive/MyDrive/VQA_project/chroma_charxiv"
COLLECTION_NAME = "charxiv_validation_images"
TOP_K_RETRIEVE = 1                   # số ảnh lấy về để đưa cho Qwen trả lời

CHECKPOINT_FILE = "/content/drive/MyDrive/VQA_project/rag_vqa_results.csv"


# ---------------------------------------------------------------------------
# Phần Retrieval (CLIP)
# ---------------------------------------------------------------------------
def get_device():
    return "cuda" if torch.cuda.is_available() else "cpu"


def load_clip(device):
    print(f"Đang tải CLIP ({CLIP_MODEL_NAME}) lên {device}...")
    model = CLIPModel.from_pretrained(CLIP_MODEL_NAME).to(device).eval()
    processor = CLIPProcessor.from_pretrained(CLIP_MODEL_NAME)
    return model, processor


@torch.no_grad()
def embed_images(clip_model, clip_processor, device, images):
    """Lưu ý: một số bản transformers có lỗi ở get_image_features() (trả về
    thẳng output thô của vision_model, thiếu chiếu qua visual_projection),
    nên ở đây gọi trực tiếp vision_model + visual_projection để tránh phụ
    thuộc vào hàm wrapper bị lỗi đó."""
    inputs = clip_processor(images=images, return_tensors="pt").to(device)
    vision_outputs = clip_model.vision_model(pixel_values=inputs["pixel_values"])
    pooled_output = vision_outputs.pooler_output
    feats = clip_model.visual_projection(pooled_output)
    feats = feats / feats.norm(p=2, dim=-1, keepdim=True)
    return feats.cpu().numpy()


@torch.no_grad()
def embed_texts(clip_model, clip_processor, device, texts):
    """Tương tự embed_images — gọi trực tiếp text_model + text_projection
    thay vì get_text_features() để tránh lỗi tương tự."""
    inputs = clip_processor(text=texts, return_tensors="pt", padding=True, truncation=True).to(device)
    text_outputs = clip_model.text_model(
        input_ids=inputs["input_ids"],
        attention_mask=inputs.get("attention_mask"),
    )
    pooled_output = text_outputs.pooler_output
    feats = clip_model.text_projection(pooled_output)
    feats = feats / feats.norm(p=2, dim=-1, keepdim=True)
    return feats.cpu().numpy()


def get_collection():
    client = chromadb.PersistentClient(path=CHROMA_DIR)
    return client.get_or_create_collection(
        name=COLLECTION_NAME,
        metadata={"hnsw:space": "cosine"},
    )


def build_index(val_ds, clip_model, clip_processor, device, n_charts, batch_size=16):
    """Mã hoá n_charts ảnh đầu tiên vào ChromaDB (id = chart_index dạng chuỗi).
    Nếu index đã tồn tại từ trước (ví dụ đã chạy rag_pipeline.py rồi), sẽ tự
    bỏ qua các ảnh đã có sẵn."""
    collection = get_collection()

    existing_ids = set(collection.get()["ids"]) if collection.count() > 0 else set()
    todo = [i for i in range(n_charts) if str(i) not in existing_ids]

    if not todo:
        print(f"Index đã có đủ {n_charts} ảnh, bỏ qua bước build.")
        return collection

    print(f"Đang mã hoá {len(todo)} ảnh còn thiếu vào vector DB...")
    for start in tqdm(range(0, len(todo), batch_size)):
        batch_idx = todo[start:start + batch_size]
        images = [val_ds[i]["image"].convert("RGB") for i in batch_idx]
        embeddings = embed_images(clip_model, clip_processor, device, images)

        collection.add(
            ids=[str(i) for i in batch_idx],
            embeddings=embeddings.tolist(),
            metadatas=[{"chart_index": i} for i in batch_idx],
        )

    print(f"Hoàn tất: vector DB hiện có {collection.count()} ảnh.")
    return collection


def retrieve_top_chart(question, clip_model, clip_processor, device, collection, top_k=TOP_K_RETRIEVE):
    """Trả về chart_index của ảnh được retrieval xếp hạng cao nhất cho câu hỏi."""
    query_emb = embed_texts(clip_model, clip_processor, device, [question])[0]
    result = collection.query(query_embeddings=[query_emb.tolist()], n_results=top_k)
    retrieved_ids = [int(x) for x in result["ids"][0]]
    return retrieved_ids[0] if retrieved_ids else None


# ---------------------------------------------------------------------------
# Phần VQA (Qwen2.5-VL) — giữ nguyên logic như baseline_qwen.py
# ---------------------------------------------------------------------------
def get_qwen_model_and_processor():
    if not torch.cuda.is_available():
        print("CẢNH BÁO: không phát hiện GPU — model 7B sẽ CHẠY RẤT CHẬM trên CPU.")

    quant_config = None
    if LOAD_IN_4BIT:
        quant_config = BitsAndBytesConfig(
            load_in_4bit=True,
            bnb_4bit_compute_dtype=torch.bfloat16,
            bnb_4bit_quant_type="nf4",
        )

    model = Qwen2_5_VLForConditionalGeneration.from_pretrained(
        QWEN_MODEL_ID,
        torch_dtype=torch.bfloat16,
        device_map="auto",
        quantization_config=quant_config,
    )
    processor = AutoProcessor.from_pretrained(QWEN_MODEL_ID)
    return model, processor


def build_prompt(question: str) -> str:
    # Giữ nguyên nội dung prompt như baseline_qwen.py để so sánh công bằng
    return (
        "You are looking at a scientific chart extracted from an arXiv paper. "
        "Answer the following question with the SHORTEST possible answer "
        "(a single word, short phrase, or number) — no explanation.\n"
        f"If the chart does not contain enough information to answer, respond exactly: '{UNANSWERABLE_LABEL}'.\n\n"
        f"Question: {question}\n"
        "Answer:"
    )


def resize_image(image, max_side=MAX_IMAGE_SIDE):
    w, h = image.size
    if max(w, h) <= max_side:
        return image
    scale = max_side / max(w, h)
    return image.resize((int(w * scale), int(h * scale)))


def ask_qwen(qwen_model, qwen_processor, image, question: str) -> str:
    prompt = build_prompt(question)
    image = resize_image(image)

    messages = [
        {
            "role": "user",
            "content": [
                {"type": "image", "image": image},
                {"type": "text", "text": prompt},
            ],
        }
    ]

    text = qwen_processor.apply_chat_template(
        messages, tokenize=False, add_generation_prompt=True
    )
    image_inputs, video_inputs = process_vision_info(messages)
    inputs = qwen_processor(
        text=[text],
        images=image_inputs,
        videos=video_inputs,
        padding=True,
        return_tensors="pt",
    ).to(qwen_model.device)

    with torch.no_grad():
        generated_ids = qwen_model.generate(**inputs, max_new_tokens=MAX_NEW_TOKENS)

    generated_ids_trimmed = [
        out_ids[len(in_ids):]
        for in_ids, out_ids in zip(inputs.input_ids, generated_ids)
    ]
    output_text = qwen_processor.batch_decode(
        generated_ids_trimmed, skip_special_tokens=True, clean_up_tokenization_spaces=False
    )
    return output_text[0].strip() if output_text else ""


def simple_match(pred: str, gold: str) -> bool:
    """Giống hệt logic trong baseline_qwen.py / baseline_gemini.py."""
    if gold is None:
        return None
    p = pred.strip().lower()
    g = str(gold).strip().lower()

    gold_unanswerable = (g == UNANSWERABLE_LABEL.lower())
    pred_unanswerable = (UNANSWERABLE_LABEL.lower() in p)
    if gold_unanswerable or pred_unanswerable:
        return gold_unanswerable == pred_unanswerable

    return g in p or p in g


def iter_questions(sample):
    """Sinh ra 5 câu hỏi (4 descriptive + 1 reasoning) từ 1 hàng dữ liệu (1 biểu đồ).
    Giống hệt baseline_qwen.py."""
    for i in range(1, 5):
        qid = sample[f"descriptive_q{i}"]
        answer = sample[f"descriptive_a{i}"]
        question_text = DESCRIPTIVE_QMAP.get(qid, f"[Không rõ template id={qid}]")
        yield {
            "slot": f"descriptive_{i}",
            "question_type": "descriptive",
            "question": question_text,
            "gold_answer": answer,
        }

    yield {
        "slot": "reasoning",
        "question_type": "reasoning",
        "sub_type": REASONING_TYPE_MAP.get(sample.get("reasoning_a_type")),
        "question": sample["reasoning_q"],
        "gold_answer": sample["reasoning_a"],
    }


# ---------------------------------------------------------------------------
# Pipeline RAG-VQA chính
# ---------------------------------------------------------------------------
def run_rag_vqa():
    device = get_device()

    print("Đang tải split 'validation' của CharXiv...")
    val_ds = load_dataset("princeton-nlp/CharXiv", split="validation")
    n_charts = min(N_CHARTS, len(val_ds))
    print(f"Chạy RAG-VQA trên {n_charts} biểu đồ đầu tiên ({n_charts * 5} câu hỏi)...")

    # --- Bước Retrieval: build/tải index CLIP ---
    clip_model, clip_processor = load_clip(device)
    collection = build_index(val_ds, clip_model, clip_processor, device, n_charts)

    # --- Checkpoint (giống baseline_qwen.py, resume được nếu bị ngắt giữa chừng) ---
    done_keys = set()
    if os.path.exists(CHECKPOINT_FILE):
        prev = pd.read_csv(CHECKPOINT_FILE)
        done_keys = set(zip(prev["chart_index"], prev["slot"]))
        results = prev.to_dict("records")
        print(f"Tìm thấy checkpoint cũ với {len(done_keys)} câu đã xử lý — chạy tiếp phần còn thiếu.")
    else:
        results = []

    # --- Tải Qwen (chỉ tải khi thực sự cần, để đỡ tốn VRAM nếu index đã đủ) ---
    print(f"Đang tải model {QWEN_MODEL_ID} (load_in_4bit={LOAD_IN_4BIT})... có thể mất vài phút.")
    qwen_model, qwen_processor = get_qwen_model_and_processor()

    for chart_idx in tqdm(range(n_charts)):
        sample = val_ds[chart_idx]

        for qa in iter_questions(sample):
            key = (chart_idx, qa["slot"])
            if key in done_keys:
                continue

            try:
                # 1) RETRIEVAL: tìm ảnh liên quan nhất tới câu hỏi (KHÔNG biết
                #    trước chart_idx đúng — mô phỏng tình huống thực tế)
                retrieved_idx = retrieve_top_chart(
                    qa["question"], clip_model, clip_processor, device, collection
                )
                retrieval_correct = (retrieved_idx == chart_idx)
                retrieved_image = val_ds[retrieved_idx]["image"]

                # 2) VQA: đưa ảnh RETRIEVAL được (có thể sai) cho Qwen trả lời
                pred = ask_qwen(qwen_model, qwen_processor, retrieved_image, qa["question"])
            except Exception as e:
                print(f"[Lỗi ở biểu đồ {chart_idx}, {qa['slot']}]: {e}")
                pred = ""
                retrieved_idx = None
                retrieval_correct = False

            correct = simple_match(pred, qa["gold_answer"])

            results.append({
                "chart_index": chart_idx,
                "slot": qa["slot"],
                "question_type": qa["question_type"],
                "sub_type": qa.get("sub_type"),
                "question": qa["question"],
                "gold_answer": qa["gold_answer"],
                "retrieved_chart_index": retrieved_idx,
                "retrieval_correct": retrieval_correct,
                "prediction": pred,
                "correct": correct,
            })

            pd.DataFrame(results).to_csv(CHECKPOINT_FILE, index=False, encoding="utf-8-sig")

        if chart_idx % 10 == 0:
            gc.collect()
            torch.cuda.empty_cache()

    df = pd.DataFrame(results)

    if df["correct"].notna().any():
        overall_acc = df["correct"].mean()
        retrieval_acc = df["retrieval_correct"].mean()
        print(f"\n=== Kết quả RAG-VQA trên {len(df)} câu hỏi — CLIP retrieval + Qwen2.5-VL ===")
        print(f"Retrieval accuracy (tìm đúng ảnh): {retrieval_acc:.2%}")
        print(f"VQA accuracy tổng thể (simple_match): {overall_acc:.2%}")

        print("\nVQA accuracy theo loại câu hỏi (descriptive vs reasoning):")
        print(df.groupby("question_type")["correct"].mean().to_string())

        print("\nRetrieval accuracy theo loại câu hỏi (descriptive vs reasoning):")
        print(df.groupby("question_type")["retrieval_correct"].mean().to_string())

        print("\nVQA accuracy TÁCH RIÊNG theo retrieval đúng/sai "
              "(cho thấy lỗi đến từ retrieval hay từ bản thân Qwen):")
        print(df.groupby("retrieval_correct")["correct"].mean().to_string())

        reasoning_df = df[df["question_type"] == "reasoning"]
        if reasoning_df["sub_type"].notna().any():
            print("\nVQA accuracy theo phân loại reasoning (Text/Number-in-Chart/General):")
            print(reasoning_df.groupby("sub_type")["correct"].mean().to_string())
    else:
        print("\nKhông tính được accuracy — kiểm tra lại dữ liệu.")

    print(f"\nĐã lưu chi tiết kết quả vào '{CHECKPOINT_FILE}'")
    print("So sánh trực tiếp với baseline_qwen_results.csv (oracle, không qua retrieval) bằng:")
    print("  pd.merge(rag_df, baseline_df, on=['chart_index','slot'], suffixes=('_rag','_baseline'))")
    return df


if __name__ == "__main__":
    run_rag_vqa()